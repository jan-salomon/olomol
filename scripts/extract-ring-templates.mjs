// Regenerates src/layout/ringTemplateData.js from RDKit's ring-system
// templates (Code/GraphMol/Depictor/TemplateSmarts.h, BSD-3-Clause).
// RDKit.js does not expose these templates, so we ship our own copy.
//
// Usage: node scripts/extract-ring-templates.mjs [rdkit-git-tag]
import { writeFileSync } from 'node:fs';

const tag = process.argv[2] ?? 'Release_2026_09_1';
const url = `https://raw.githubusercontent.com/rdkit/rdkit/${tag}/Code/GraphMol/Depictor/TemplateSmarts.h`;
const response = await fetch(url);
if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
const header = await response.text();

// Each template is one C string literal on its own line: a CXSMARTS with 2D coordinates.
const templates = [...header.matchAll(/^\s+"(.*)",\s*$/gm)].map((m) => m[1]);
const declared = Number(header.match(/std::array<const char\*, (\d+)>/)?.[1]);
if (!templates.length || templates.length !== declared) {
  throw new Error(`expected ${declared} templates, found ${templates.length}`);
}

writeFileSync(
  new URL('../src/layout/ringTemplateData.js', import.meta.url),
  `// GENERATED by scripts/extract-ring-templates.mjs from RDKit ${tag}:
// Code/GraphMol/Depictor/TemplateSmarts.h
// Copyright (C) 2023 Schrödinger, LLC. Part of the RDKit, BSD-3-Clause
// license (public/THIRD_PARTY_LICENSES/rdkit-LICENSE.txt).
// Each entry is a ring-system CXSMARTS with 2D coordinates.
export default [
${templates.map((t) => `  ${JSON.stringify(t)},`).join('\n')}
];
`,
);
console.log(`wrote ${templates.length} templates`);
